func generateGRPC(data *parser.CLIData) ([]byte, error) {
	tmpl, err := template.New("grpc").Parse(grpcTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
